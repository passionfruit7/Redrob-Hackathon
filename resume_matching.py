# Sort compound phrases longest-first for greedy matching
compound_phrases = sorted(
    [key for key in SKILL_ALIASES if " " in key or "/" in key or "-" in key],
    key=lambda phrase: -len(phrase)
)

# Normalize the job descriptions
normalized_job_descriptions = {}
for jd_name, description in job_descriptions.items():
    tokens = [skill.strip() for skill in description.lower().split(',')]
    normalized_skills_list = []
    seen = set()
    for token in tokens:
        matched = None
        for phrase in compound_phrases:
            if phrase in token:
                matched = SKILL_ALIASES[phrase]
                break
        if not matched:
            matched = SKILL_ALIASES.get(token)
        if matched and matched not in seen:
            seen.add(matched)
            normalized_skills_list.append(matched)
    normalized_job_descriptions[jd_name] = normalized_skills_list

# Compute binary vectors for job descriptions
binary_vectors = {}
for jd_name, skills in normalized_job_descriptions.items():
    binary_vector = [1.0 if skill in skills else 0.0 for skill in vocabulary]
    binary_vectors[jd_name] = binary_vector

# Compute cosine similarity
cosine_similarities = {}
for name, tfidf_vector in tfidf_vectors.items():
    cosine_similarities[name] = {}
    for jd_name, binary_vector in binary_vectors.items():
        dot_product = sum(a * b for a, b in zip(tfidf_vector, binary_vector))
        magnitude_a = math.sqrt(sum(a ** 2 for a in tfidf_vector))
        magnitude_b = math.sqrt(sum(b ** 2 for b in binary_vector))
        if magnitude_a * magnitude_b != 0:
            cosine_similarities[name][jd_name] = dot_product / (magnitude_a * magnitude_b)
        else:
            cosine_similarities[name][jd_name] = 0.0

# Output Top 3 candidates per JD
for jd_name in job_descriptions:
    sorted_candidates = sorted(
        cosine_similarities.items(),
        key=lambda x: (-x[1][jd_name], x[0])
    )
    print(f"{jd_name}:")
    for candidate, similarities in sorted_candidates[:3]:
        print(f"  {candidate}({similarities[jd_name]:.2f})")
