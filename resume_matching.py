import math

def normalize_and_deduplicate_skills(raw_skills):
    """
    Normalize and deduplicate skills from a raw string.

    Args:
        raw_skills (str): Raw skills string.

    Returns:
        list: List of normalized and deduplicated skills.
    """
    # Split raw skills on commas
    skills = [skill.strip() for skill in raw_skills.split(',')]

    # Create a dictionary to store the normalized skills
    normalized_skills = {}

    # Iterate over each skill
    for skill in skills:
        # Lowercase the skill
        skill = skill.lower()

        # Check if the skill is a multi-word phrase
        for key in SKILL_ALIASES:
            if key in skill:
                # If the skill is a multi-word phrase, use the alias
                normalized_skill = SKILL_ALIASES[key]
                if normalized_skill not in normalized_skills:
                    normalized_skills[normalized_skill] = True
                break
        else:
            # If the skill is not a multi-word phrase, check if it's in the SKILL_ALIASES dictionary
            if skill in SKILL_ALIASES:
                # If the skill is in the dictionary, use the alias
                normalized_skill = SKILL_ALIASES[skill]
                if normalized_skill not in normalized_skills:
                    normalized_skills[normalized_skill] = True

    # Return the list of normalized and deduplicated skills
    return list(normalized_skills.keys())

